function ensureDirectory(directory) {
  fs.mkdirSync(directory, { recursive: true })
}

function normalizeText(value) {
  return String(value || "")
    .trim()
    .toLowerCase()
    .replace(/\s+/g, " ")
}

function roundCurrency(value) {
  const numeric = Number(value || 0)
  if (!Number.isFinite(numeric)) return 0
  return Math.round(numeric * 100) / 100
}

function normalizeDateOnly(value) {
  const date = value instanceof Date ? value : new Date(value)
  if (Number.isNaN(date.getTime())) return null
  return new Date(Date.UTC(date.getUTCFullYear(), date.getUTCMonth(), date.getUTCDate()))
}

function numericCellValue(value) {
  if (typeof value === "number" && Number.isFinite(value)) return value
  if (value && typeof value === "object" && value.result !== undefined) return numericCellValue(value.result)
  if (typeof value === "string") {
    const parsed = Number.parseFloat(value.replace(/,/g, ""))
    return Number.isFinite(parsed) ? parsed : 0
  }
  return 0
}

function closeEnough(actual, expected) {
  return Math.abs(roundCurrency(actual) - roundCurrency(expected)) <= AMOUNT_TOLERANCE
}

function mapToObject(map) {
  return Object.fromEntries(Array.from(map.entries()).map(([key, value]) => [key, roundCurrency(value)]))
}

function hasTimeoutMarker(value) {
  if (!value) return false
  if (Array.isArray(value)) return value.some((item) => hasTimeoutMarker(item))
  if (typeof value !== "object") return false
  if (value.isTimeout === true) return true
  return Object.entries(value).some(([key, entry]) => {
    const normalizedKey = normalizeText(key).replace(/[_-]/g, "")
    if (
      typeof entry === "string" &&
      ["code", "errorcode", "failurecode", "reason", "errorreason", "failurereason", "message"].includes(normalizedKey) &&
      /timeout|timed out/i.test(entry)
    ) {
      return true
    }
    return hasTimeoutMarker(entry)
  })
}

function latestTestingTemplatePath() {
  const dir = path.join(ROOT_DIR, "uploads", "cash-flow", "template-analyses")
  if (!fs.existsSync(dir)) return DEFAULT_TEMPLATE
  const candidates = fs
    .readdirSync(dir)
    .filter((fileName) => /Testing_Template_2.*\.xlsx$/i.test(fileName))
    .map((fileName) => {
      const fullPath = path.join(dir, fileName)
      return { fullPath, mtimeMs: fs.statSync(fullPath).mtimeMs }
    })
    .sort((left, right) => right.mtimeMs - left.mtimeMs)
  return candidates[0]?.fullPath || DEFAULT_TEMPLATE
}

async function createRenamedTemplate({ sourceTemplatePath, outputPath }) {
  const workbook = await readWorkbookFromFile({
    filePath: sourceTemplatePath,
    label: "Testing Template 2",
    ValidationErrorCtor: CashFlowService.CashFlowValidationError,
  })
  const worksheet = workbook.getWorksheet("Cash Flow") || workbook.worksheets[0]
  const headerRow = worksheet.getRow(9)
  const sectionColumn = normalizeText(headerRow.getCell(2).text) === "section" ? 2 : 1
  const lineItemColumn = normalizeText(headerRow.getCell(3).text) === "line item" ? 3 : sectionColumn + 1
  ROW_RENAMES.forEach((rename, rowIndex) => {
    worksheet.getRow(rowIndex).getCell(sectionColumn).value = rename.section
    worksheet.getRow(rowIndex).getCell(lineItemColumn).value = rename.label
  })
  await workbook.xlsx.writeFile(outputPath)
}

function getAssignmentLookup(assignments = []) {
  return new Map(
    assignments.map((assignment) => [
      `${normalizeText(assignment.normalized_account || assignment.account_name)}:${assignment.direction}`,
      assignment,
    ]),
  )
}

async function buildExpectedTruth({ tbFilePath, glFilePath, dateStart, dateEnd }) {
  const trialBalance = await CashFlowService.parseTrialBalanceFile(tbFilePath)
  const generalLedger = await CashFlowService.parseGeneralLedgerFile(glFilePath, {
    cashAccountName: trialBalance.cashAccountName,
  })
  const start = normalizeDateOnly(dateStart)
  const end = normalizeDateOnly(dateEnd)
  const accountDirectionTotals = new Map()
  const unknownMovementKeys = new Set()
  const totals = {
    total_inflows: 0,
    total_outflows: 0,
    net_cash_flow: 0,
  }

  generalLedger.movements.forEach((movement) => {
    const movementDate = normalizeDateOnly(movement.date)
    if (!movementDate || movementDate < start || movementDate > end) return
    const direction = Number(movement.amount || 0) >= 0 ? "inflow" : "outflow"
    const key = `${normalizeText(movement.account_name)}:${direction}`
    if (!EXPECTED_ASSIGNMENT_CONCEPTS.has(key)) {
      unknownMovementKeys.add(key)
      return
    }
    const absAmount = Math.abs(Number(movement.amount || 0))
    accountDirectionTotals.set(key, roundCurrency((accountDirectionTotals.get(key) || 0) + absAmount))
    if (direction === "inflow") totals.total_inflows = roundCurrency(totals.total_inflows + absAmount)
    else totals.total_outflows = roundCurrency(totals.total_outflows + absAmount)
    totals.net_cash_flow = roundCurrency(totals.net_cash_flow + Number(movement.amount || 0))
  })

  return {
    totals,
    account_direction_totals: accountDirectionTotals,
    unknown_movement_keys: Array.from(unknownMovementKeys),
  }
}

function buildExpectedBucketTotals({ report, expectedTruth }) {
  const assignmentLookup = getAssignmentLookup(report.mapping?.final_bucket_assignments || [])
  const bucketTotals = new Map()
  expectedTruth.account_direction_totals.forEach((amount, accountDirectionKey) => {
    const assignment = assignmentLookup.get(accountDirectionKey)
    if (!assignment?.bucket_key) return
    bucketTotals.set(assignment.bucket_key, roundCurrency((bucketTotals.get(assignment.bucket_key) || 0) + amount))
  })
  return bucketTotals
}

async function validateWorkbookOutput({ outputFilePath, config, expectedBucketTotals }) {
  const failures = []
  const workbookBucketTotals = new Map()
  const workbook = await readWorkbookFromFile({
    filePath: outputFilePath,
    label: "cash-flow output",
    ValidationErrorCtor: CashFlowService.CashFlowValidationError,
  })
  const worksheet = workbook.getWorksheet(config.sheet_name) || workbook.worksheets[0]
  const bucketLookup = new Map((config.bucket_bindings || []).map((bucket) => [bucket.bucket_key, bucket]))

  expectedBucketTotals.forEach((expected, bucketKey) => {
    const bucket = bucketLookup.get(bucketKey)
    if (!bucket) {
      failures.push(`output workbook cannot validate missing bucket ${bucketKey}`)
      return
    }
    const signedTotal = (bucket.cells || []).reduce((sum, binding) => {
      if (!binding?.cell) return sum
      return sum + numericCellValue(worksheet.getCell(binding.cell).value)
    }, 0)
    const comparableTotal = bucket.direction === "outflow" ? Math.abs(signedTotal) : signedTotal
    workbookBucketTotals.set(bucketKey, roundCurrency(comparableTotal))
    if (!closeEnough(comparableTotal, expected)) {
      failures.push(`output workbook bucket ${bucketKey} total mismatch: expected ${expected}, got ${roundCurrency(comparableTotal)}`)
    }
  })

  return {
    failures,
    workbook_bucket_totals: workbookBucketTotals,
  }
}

function validateResult({ ingestion, report, expectedTruth, expectedBucketTotals }) {
  const failures = []
  const semanticRepair = ingestion.llm_meta_json?.semantic_repair || null
  const configuredPeriodCount = Number(ingestion.suggested_config_json?.period_axis?.labels?.length || 0)
  if (!String(ingestion.analysis_source || "").includes("llm")) {
    failures.push(`template ingestion did not use LLM path: ${ingestion.analysis_source}`)
  }
  if (configuredPeriodCount < EXPECTED_PERIOD_COUNT) {
    failures.push(`template config period axis was truncated: expected ${EXPECTED_PERIOD_COUNT} periods, got ${configuredPeriodCount}`)
  }
  if (!semanticRepair?.attempted) {
    failures.push("template semantic repair was not attempted")
  }
  if (semanticRepair?.failure_code) {
    failures.push(`template semantic repair failed: ${semanticRepair.failure_reason || semanticRepair.failure_code}`)
  }
  if (ingestion.needs_human_review) {
    failures.push(`template ingestion needs human review: ${(ingestion.issues || []).join("; ")}`)
  }

  const assistance = report.mapping?.assistance_summary || {}
  if (!assistance.enabled) {
    failures.push("runtime LLM assistance was not enabled")
  }
  if (!assistance.attempted) {
    failures.push("runtime LLM assistance was not attempted")
  }
  if (assistance.failed) {
    failures.push(`runtime LLM assistance failed: ${assistance.failureReason || assistance.failureCode || "unknown failure"}`)
  }
  if (Number(assistance.acceptedCount || 0) <= 0) {
    failures.push("runtime LLM did not accept or confirm any mapping")
  }
  if (hasTimeoutMarker(ingestion.llm_meta_json) || hasTimeoutMarker(assistance)) {
    failures.push("LLM timeout occurred; timeouts are hard failures for this evaluation")
  }
  if (expectedTruth.unknown_movement_keys.length) {
    failures.push(`expected truth is missing tags for GL movements: ${expectedTruth.unknown_movement_keys.join(", ")}`)
  }

  Object.entries(expectedTruth.totals).forEach(([key, expected]) => {
    const actual = Number(report.preview?.totals?.[key] || 0)
    if (!closeEnough(actual, expected)) {
      failures.push(`report total ${key} mismatch: expected ${expected}, got ${roundCurrency(actual)}`)
    }
  })
  expectedBucketTotals.forEach((expected, bucketKey) => {
    const actual = Number(report.preview?.totals?.bucket_totals?.[bucketKey] || 0)
    if (!closeEnough(actual, expected)) {
      failures.push(`report bucket ${bucketKey} total mismatch: expected ${expected}, got ${roundCurrency(actual)}`)
    }
  })

  const fallbackAssignments = (report.mapping?.final_bucket_assignments || []).filter((assignment) =>
    ["fallback", "derived_operating"].includes(normalizeText(assignment.source || assignment.grounding_status)),
  )
  if (fallbackAssignments.length) {
    failures.push(`fallback assignments remained: ${fallbackAssignments.map((item) => item.normalized_account).join(", ")}`)
  }

  const lookup = getAssignmentLookup(report.mapping?.final_bucket_assignments || [])
  EXPECTED_ASSIGNMENT_CONCEPTS.forEach((expectedConcept, key) => {
    const assignment = lookup.get(key)
    if (!assignment) {
      failures.push(`missing mapping for ${key}`)
      return
    }
    if (assignment.semantic_key !== expectedConcept) {
      failures.push(`wrong concept for ${key}: expected ${expectedConcept}, got ${assignment.semantic_key || "none"} (${assignment.bucket_key})`)
    }
  })

  return failures
}

function writeDiagnostics({ outputDir, payload }) {
  const jsonPath = path.join(outputDir, "diagnostics.json")
  const mdPath = path.join(outputDir, "diagnostics.md")
  fs.writeFileSync(jsonPath, JSON.stringify(payload, null, 2))
  const lines = [
    "# Testing Template 2 Adversarial LLM Evaluation",
    "",
    `- Status: ${payload.status}`,
    `- Template model: ${payload.template_model || "n/a"}`,
    `- Runtime model: ${payload.runtime_model || "n/a"}`,
    `- Runtime attempted: ${Boolean(payload.runtime_assistance?.attempted)}`,
    `- Runtime accepted: ${payload.runtime_assistance?.acceptedCount || 0}`,
    `- Runtime rejected: ${payload.runtime_assistance?.rejectedCount || 0}`,
    `- Template semantic repair attempted: ${Boolean(payload.template_semantic_repair?.attempted)}`,
    "",
  ]
  if (payload.failures.length) {
    lines.push("## Failures", "")
    payload.failures.forEach((failure) => lines.push(`- ${failure}`))
    lines.push("")
  }
  lines.push("## Files", "")
  Object.entries(payload.files).forEach(([label, filePath]) => lines.push(`- ${label}: ${filePath}`))
  fs.writeFileSync(mdPath, `${lines.join("\n")}\n`)
  return { jsonPath, mdPath }
}

async function main() {
  const timestamp = new Date().toISOString().replace(/[:.]/g, "-")
  const outputDir = path.join(OUTPUT_ROOT, timestamp)
  ensureDirectory(outputDir)

  const sourceTemplatePath = process.env.TESTING_TEMPLATE_2_PATH || latestTestingTemplatePath()
  const tbFilePath = process.env.TESTING_TEMPLATE_2_TB_PATH || DEFAULT_TB
  const glFilePath = process.env.TESTING_TEMPLATE_2_GL_PATH || DEFAULT_GL
  const renamedTemplatePath = path.join(outputDir, "Testing_Template_2_adversarial_names.xlsx")
  const outputFilePath = path.join(outputDir, "cash_flow_output.xlsx")

  await createRenamedTemplate({ sourceTemplatePath, outputPath: renamedTemplatePath })

  const ingestionStarted = Date.now()
  const ingestion = await CashFlowTemplateIngestionService.ingestTemplateSchema({
    templatePath: renamedTemplatePath,
    sourceFileName: "Testing_Template_2_adversarial_names.xlsx",
    forceLlm: true,
  })
  const ingestionLatencyMs = Date.now() - ingestionStarted

  const reportStarted = Date.now()
  const report = await CashFlowService.generateCashFlowReport({
    templatePath: renamedTemplatePath,
    templateConfig: ingestion.suggested_config_json,
    tbFilePath,
    glFilePath,
    dateStart: DATE_START,
    dateEnd: DATE_END,
    outputFilePath,
    learnedMappings: [],
    useRuntimeMappingAssistance: true,
  })
  const reportLatencyMs = Date.now() - reportStarted

  const expectedTruth = await buildExpectedTruth({
    tbFilePath,
    glFilePath,
    dateStart: DATE_START,
    dateEnd: DATE_END,
  })
  const expectedBucketTotals = buildExpectedBucketTotals({ report, expectedTruth })
  const reportFailures = validateResult({ ingestion, report, expectedTruth, expectedBucketTotals })
  const workbookValidation = await validateWorkbookOutput({
    outputFilePath,
    config: ingestion.suggested_config_json,
    expectedBucketTotals,
  })
  const failures = [...reportFailures, ...workbookValidation.failures]
  const payload = {
    status: failures.length ? "failed" : "passed",
    generated_at: new Date().toISOString(),
    failures,
    ingestion_latency_ms: ingestionLatencyMs,
    report_latency_ms: reportLatencyMs,
    template_model: ingestion.llm_meta_json?.model || null,
    runtime_model: report.mapping?.assistance_summary?.model || null,
    analysis_source: ingestion.analysis_source,
    confidence: ingestion.confidence,
    issues: ingestion.issues || [],
    required_anchors: ingestion.required_anchors || [],
    template_semantic_repair: ingestion.llm_meta_json?.semantic_repair || null,
    runtime_assistance: report.mapping?.assistance_summary || null,
    account_profile_summary: report.mapping?.account_profile_summary || null,
    expected_totals: expectedTruth.totals,
    expected_bucket_totals: mapToObject(expectedBucketTotals),
    workbook_bucket_totals: mapToObject(workbookValidation.workbook_bucket_totals),
    final_assignments: report.mapping?.final_bucket_assignments || [],
    auto_mappings_created: report.mapping?.auto_mappings_created || [],
    low_confidence_mappings: report.mapping?.low_confidence_mappings || [],
    totals: report.preview?.totals || null,
    warnings: report.warnings || [],
    files: {
      source_template: sourceTemplatePath,
      renamed_template: renamedTemplatePath,
      trial_balance: tbFilePath,
      general_ledger: glFilePath,
      report_output: outputFilePath,
    },
  }
  const diagnostics = writeDiagnostics({ outputDir, payload })

  console.log(`Testing Template 2 adversarial LLM evaluation ${payload.status}`)
  console.log(`Diagnostics JSON: ${diagnostics.jsonPath}`)
  console.log(`Diagnostics Markdown: ${diagnostics.mdPath}`)
  console.log(`Template model: ${payload.template_model || "n/a"} (${ingestionLatencyMs}ms)`)
  console.log(`Runtime model: ${payload.runtime_model || "n/a"} (${reportLatencyMs}ms)`)
  console.log(`Runtime attempted: ${Boolean(payload.runtime_assistance?.attempted)}`)
  console.log(`Runtime accepted: ${payload.runtime_assistance?.acceptedCount || 0}`)
  failures.forEach((failure) => console.log(`- ${failure}`))

  process.exit(failures.length ? 1 : 0)
}

main().catch((error) => {
  console.error("Testing Template 2 adversarial LLM evaluation crashed")
  console.error(error)
  process.exit(1)
})
